#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
通用版「學生名單 CSV → students.js」轉換器

使用方式：
    python build_students.py <csv_path> <output_js_path> [--cert-prefix=XXX]

或匯入後客製化：

    from build_students import build, default_normalize

    build(
        csv_path="...",
        output_js_path="...",
        column_map={
            "email":  "電子郵件地址",
            "name":   "姓名 (請填寫正確，使用於證書上)",
            "school": "學校名稱（請寫學校名）",
            ...
        },
        filter_fn=lambda row: "不同意" not in row.get("您是否同意以上線上課程聲明", ""),
        cert_prefix="2026-AISEA",
    )
"""

import os
import sys
import csv
import json
import argparse


def default_normalize(s):
    if s is None:
        return ""
    return s.strip().replace("　", " ")


DEFAULT_COLUMN_MAP = {
    "email": "電子郵件地址",
    "name": "姓名",
    "school": "學校名稱",
    "dept": "科系",
    "grade": "年級",
    "class": "班級",
}


def build(
    csv_path,
    output_js_path,
    column_map=None,
    filter_fn=None,
    cert_prefix="CERT",
    encoding="utf-8-sig",
):
    """
    參數：
      csv_path: 輸入 CSV 路徑
      output_js_path: 輸出 .js 路徑
      column_map: dict，{內部 key: CSV 欄位名}
      filter_fn: callable(row_dict) -> bool，回傳 True 才保留
      cert_prefix: 證書編號前綴
      encoding: CSV 編碼（Google Form 匯出建議 utf-8-sig）
    """
    column_map = column_map or DEFAULT_COLUMN_MAP

    if not os.path.exists(csv_path):
        raise FileNotFoundError(csv_path)

    students_by_email = {}

    with open(csv_path, "r", encoding=encoding, newline="") as f:
        reader = csv.DictReader(f)
        for row in reader:
            if filter_fn and not filter_fn(row):
                continue

            record = {}
            for key, col_name in column_map.items():
                record[key] = default_normalize(row.get(col_name, ""))

            email = record.get("email", "").lower()
            name = record.get("name", "")
            if not email or not name:
                continue

            record["email"] = email
            students_by_email[email] = record

    students = list(students_by_email.values())
    students.sort(key=lambda x: x["email"])

    for i, s in enumerate(students, start=1):
        s["certId"] = "{}-{:04d}".format(cert_prefix, i)

    os.makedirs(os.path.dirname(output_js_path), exist_ok=True)
    with open(output_js_path, "w", encoding="utf-8") as f:
        f.write("// Generated by edu-cert-maker / build_students.py\n")
        f.write("// Total students: {}\n\n".format(len(students)))
        f.write("const STUDENTS_DATA = ")
        json.dump(students, f, ensure_ascii=False, indent=2)
        f.write(";\n")

    return len(students)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("csv_path", help="輸入 CSV 路徑")
    parser.add_argument("output_js_path", help="輸出 .js 路徑")
    parser.add_argument("--cert-prefix", default="CERT", help="證書編號前綴")
    parser.add_argument(
        "--filter-keyword",
        default="不同意",
        help="若任一欄位含此關鍵字則過濾掉（預設『不同意』）",
    )
    args = parser.parse_args()

    def has_keyword(row):
        for v in row.values():
            if v and args.filter_keyword in v:
                return True
        return False

    count = build(
        csv_path=args.csv_path,
        output_js_path=args.output_js_path,
        filter_fn=lambda row: not has_keyword(row),
        cert_prefix=args.cert_prefix,
    )
    print("[DONE] {} students written to {}".format(count, args.output_js_path))


if __name__ == "__main__":
    main()
